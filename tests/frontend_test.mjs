import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { normalizeSnapshot, seedDemo, reduceLocal, safeURL, supportedRoutes } = require('../assets/app.js');

const fixture = seedDemo();
assert.equal(fixture.metadata.synthetic, true);
assert.ok(fixture.evidence.length >= 3);
assert.ok(fixture.flows[0].steps.length >= 2);
assert.deepEqual(supportedRoutes, ['overview', 'evidence', 'graph', 'flows', 'correlations', 'timeline', 'notes']);
assert.equal(safeURL('javascript:alert(1)'), null);
assert.equal(safeURL('file:///etc/passwd'), null);
assert.equal(safeURL('https://example.org/'), 'https://example.org/');
assert.equal(normalizeSnapshot({ state: fixture }).evidence.length, fixture.evidence.length);

let next = reduceLocal(fixture, '/api/evidence', { title: 'Manual observation', content: '<script>never executed</script>', source_url: 'https://example.org/new', kind: 'note' });
assert.equal(next.evidence.length, fixture.evidence.length + 1);
assert.equal(fixture.evidence.length, 4, 'Reducers preserve original source state');
assert.equal(next.evidence[0].content, '<script>never executed</script>', 'Source strings remain uninterpreted data');
assert.equal(next.evidence[0].status, 'unreviewed');
assert.throws(() => reduceLocal(fixture, '/api/evidence', { title: 'bad', source_url: 'javascript:alert(1)' }));
assert.throws(() => reduceLocal(fixture, '/api/evidence', { title: '   ' }));
const added = next.evidence[0].id;
next = reduceLocal(next, '/api/evidence/review', { evidence_id: added, status: 'corroborated', note: 'Observed directly' });
assert.equal(next.evidence[0].status, 'corroborated');
assert.equal(next.evidence[0].review_note, 'Observed directly');
assert.throws(() => reduceLocal(next, '/api/evidence/review', { evidence_id: added, status: 'proven_owner' }));

next = reduceLocal(next, '/api/notes', { content: 'Reasoned note', evidence_ids: [added] });
assert.equal(next.notes[0].evidence_ids[0], added);
assert.throws(() => reduceLocal(next, '/api/notes', { content: 'Unsupported', evidence_ids: ['missing'] }));
next = reduceLocal(next, '/api/entities', { kind: 'url', value: 'https://example.org/new', label: 'Source page' });
const entity = next.entities.at(-1).id;
assert.throws(() => reduceLocal(next, '/api/links', { source_id: entity, target_id: 'en_channel', relation: 'links_to', evidence_ids: [] }));
next = reduceLocal(next, '/api/links', { source_id: entity, target_id: 'en_channel', relation: 'links_to', evidence_ids: [added], note: 'Explicit link' });
assert.equal(next.links.at(-1).status, 'analyst_assertion');
assert.throws(() => reduceLocal(next, '/api/links', { source_id: entity, target_id: entity, evidence_ids: [added] }));
assert.throws(() => reduceLocal(next, '/api/correlations/review', { id: 'co_links', decision: 'accepted', note: '' }));
const entitiesBeforeReview = next.entities.length;
next = reduceLocal(next, '/api/correlations/review', { id: 'co_links', decision: 'accepted', note: 'Both direct links support a working lead only.' });
assert.equal(next.correlations[0].status, 'accepted');
assert.equal(next.entities.length, entitiesBeforeReview, 'Correlation review never merges identities');
next = reduceLocal(next, '/api/flows', { title: 'New research plan', steps: [] });
const flow = next.flows.at(-1);
next = reduceLocal(next, '/api/flows/steps', { flow_id: flow.id, command: 'http', target: 'https://example.org', options: {} });
assert.equal(next.flows.at(-1).steps[0].status, 'pending');
assert.throws(() => reduceLocal(next, '/api/tools/run', { command: 'http', target: 'https://example.org' }), /requires the local/);
assert.ok(next.activity.length > fixture.activity.length);
console.log('Frontend workflow checks passed.');
